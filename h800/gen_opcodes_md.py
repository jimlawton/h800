"""
Opcode Markdown Generator for Honeywell H-800/H-1800

Generates a Markdown document summarizing all defined instruction opcodes,
their metadata fields, and enumeration counts. Intended to keep
`docs/generated/opcodes.md` up to date after opcode refactors.

Usage (from project root or with package import):

    python -m h800.gen_opcodes_md               # writes docs/generated/opcodes.md
    python -m h800.gen_opcodes_md --output /tmp/opcodes.md
    python -m h800.gen_opcodes_md --no-samples
    python -m h800.gen_opcodes_md --sample-limit 3

The generator provides:
    - A summary table of all mnemonics with metadata (type, bits 2-3, bit7, opcode value).
    - Enumeration counts (# of distinct 12-bit encodings) per mnemonic.
    - A collision note for PRA / PRD / PRO (shared opcode space).
    - Optional samples (first N encodings) per mnemonic.

Per-mnemonic encoding counts (derived from current design):
    maskable: 64 masked (2 sequences * 32 masks) + 16 unmasked (2 sequences * 2^3 operand flags) = 80
    unmasked: 16 (2 sequences * 2^3 operand flags)
    peripheral: 64 (paddr 0..63, bit7=1)
    print: 16 (2 sequences * 2^3 operand flags) — PRA/PRD/PRO share all values
    simulator: 2 (sequence bit only; opcode constant)
    pseudo/other: 0 (no 12-bit word encodings)

Print collision:
    PRA, PRD, PRO enumerate identical numeric opcode values; decoding any such word lists all three.

NOTE:
    The script imports `OPCODES` (metadata) and uses `enumerate_encodings` plus formatting helpers
    defined in the h800 package.

"""

from __future__ import annotations

import argparse
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from pathlib import Path

from .cli import EncodedVariant, enumerate_encodings, fmt_binary, fmt_octal
from .instruction import decode_instruction
from .instructions import OPCODES

# ---------------------------------------------------------------------------
# Data extraction helpers
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class OpcodeSummary:
    mnemonic: str
    type: str
    b23: int | None
    b7: int | None
    op: int  # bits 8-12
    encoding_count: int


def classify_type(meta) -> str:
    return getattr(meta, "type", "unmasked")


def count_encodings(mnemonic: str) -> int:
    meta = OPCODES[mnemonic]
    t = classify_type(meta)
    if t == "maskable":
        return 80
    if t == "unmasked":
        return 16
    if t == "peripheral":
        return 64
    if t == "print":
        return 16
    if t == "simulator":
        return 2
    return 0  # pseudo / constants not represented here


def iter_opcode_summaries() -> Iterable[OpcodeSummary]:
    for mnemonic, meta in OPCODES.items():
        yield OpcodeSummary(
            mnemonic=mnemonic,
            type=classify_type(meta),
            b23=getattr(meta, "b23", None),
            b7=getattr(meta, "b7", None),
            op=getattr(meta, "op", 0),
            encoding_count=count_encodings(mnemonic),
        )


# ---------------------------------------------------------------------------
# Markdown generation
# ---------------------------------------------------------------------------


def format_meta_row(s: OpcodeSummary) -> str:
    b23 = "-" if s.b23 is None else f"{s.b23:02b}"
    b7 = "-" if s.b7 is None else f"{s.b7}"
    op_oct = f"{s.op:02o}"
    op_dec = f"{s.op}"
    return f"| {s.mnemonic:<6} | {s.type:<11} | {b23:^5} | {b7:^3} | {op_oct:^6} | {op_dec:^6} | {s.encoding_count:^7} |"


def generate_samples(mnemonic: str, limit: int | None) -> list[EncodedVariant]:
    # Use enumeration utility; for print mnemonics we only show the requested one.
    return enumerate_encodings(
        mnemonic,
        include_all_print=False,
        sample_limit=limit,
    )


def build_markdown(include_samples: bool = True, sample_limit: int | None = 5) -> str:
    lines: list[str] = []
    lines.append("# Honeywell H-800/H-1800 Opcode Summary")
    lines.append("")
    lines.append("This document is auto-generated by `h800.gen_opcodes_md`. Do not edit manually.")
    lines.append("")
    lines.append("## Table: Opcode Metadata")
    lines.append("")
    lines.append("| Mnemonic | Type        | b23   | b7  | op(oct) | op(dec) | Count  |")
    lines.append("|----------|-------------|-------|-----|---------|---------|--------|")
    for summary in sorted(iter_opcode_summaries(), key=lambda s: (s.type, s.mnemonic)):
        lines.append(format_meta_row(summary))
    lines.append("")
    lines.append("Type legend:")
    lines.append(
        "- maskable: supports masked form (bit7=1, mask 0..31) and unmasked form (bit7=0, bits2-3 variant + operand flags)."
    )
    lines.append("- unmasked: operand flags (a,b,c) + bits2-3 variant.")
    lines.append("- peripheral: 6-bit peripheral address (bits1-6) + bit7=1.")
    lines.append(
        "- print: shares collision space (PRA/PRD/PRO) with operand flags; decoding lists all three."
    )
    lines.append("- simulator: sequence bit selects one of two invariant opcode words.")
    lines.append("")
    lines.append("### Collision Note")
    lines.append(
        "Print mnemonics PRA, PRD, PRO share identical numeric opcode encodings; differentiation occurs at assembly time, not at binary disassembly."
    )
    lines.append("")
    if include_samples:
        lines.append("## Sample Encodings (First N per mnemonic)")
        lines.append("")
        lines.append(f"Sample limit: {sample_limit if sample_limit is not None else 'ALL'}")
        lines.append("")
        for summary in sorted(iter_opcode_summaries(), key=lambda s: (s.type, s.mnemonic)):
            if summary.encoding_count == 0:
                continue
            samples = generate_samples(summary.mnemonic, sample_limit)
            if not samples:
                continue
            lines.append(f"### {summary.mnemonic} ({summary.type}, total {summary.encoding_count})")
            lines.append("")
            lines.append("| Octal  | Binary (12b)     | Detail |")
            lines.append("|--------|------------------|--------|")
            for ev in samples:
                lines.append(f"| {fmt_octal(ev.word)} | {fmt_binary(ev.word)} | {ev.detail} |")
            lines.append("")
    lines.append("## Validation / Regeneration")
    lines.append(
        "To regenerate this file: `python -m h800.gen_opcodes_md > docs/generated/opcodes.md`"
    )
    lines.append("")
    lines.append("## Disassembly Example")
    example_word = generate_samples("BA", 1)[0].word
    decode_info = decode_instruction(example_word, OPCODES)
    lines.append(
        f"Word `BA` sample {fmt_octal(example_word)} decodes to candidates: {', '.join(decode_info['mnemonics'])}"
    )
    lines.append("")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------


def parse_args(argv: Sequence[str] | None = None):
    p = argparse.ArgumentParser(
        prog="h800.gen_opcodes_md",
        description="Generate Markdown opcode table for Honeywell H-800/H-1800.",
    )
    p.add_argument(
        "-o",
        "--output",
        default="docs/generated/opcodes.md",
        help="Destination markdown file path (default: docs/generated/opcodes.md).",
    )
    p.add_argument(
        "--no-samples",
        action="store_true",
        help="Exclude sample encoding listings (faster, smaller file).",
    )
    p.add_argument(
        "--sample-limit",
        type=int,
        default=5,
        help="Max samples per mnemonic (default: 5, use 0 for ALL).",
    )
    return p.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(argv)
    include_samples = not args.no_samples
    limit = None if args.sample_limit == 0 else args.sample_limit
    md = build_markdown(include_samples=include_samples, sample_limit=limit)
    out_path = Path(args.output)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(md, encoding="utf-8")
    print(f"Wrote opcode summary to {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())


__all__ = [
    "OpcodeSummary",
    "build_markdown",
    "main",
]
